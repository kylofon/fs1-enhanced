/* Natives for subphase 3.18 keyboard and controls (see docs/PHASE3_PLAN.md and
 * docs/subphases/3.18.md): the keyboard interrupt int9_keyboard (0050:0970), key_dispatch
 * (09AB), every key handler of the key_handlers table (DS:05B1), the routines they share
 * (set_flaps, the control indicators, ...) and key_repeat_accel (109B).
 *
 * The emulated keyboard path stays: SDL -> pc_key_event -> port 60h -> IRQ1 -> this native.
 *
 * Like 3.16 (editor.c), the routines are transliterated on the emulated registers, so every
 * register, segment register and memory byte (including the stack words written by CALL and
 * PUSH) ends as the original leaves it; flags are not kept except IF (none of the callers reads
 * them, and the interrupt's IRET restores them). Memory goes through the generated accessors of
 * game/state.h, on the live DS.
 *
 * Cycles: run(from, to) adds the cpu8086.c cost of every original instruction in [from, to)
 * (table keys_cycles.h, generated by tools/gen_keys_cycles.py), taken() the extra cost of a
 * conditional jump that was taken. Every entry's .cycles is ENTRY_CYCLES and is subtracted
 * again, so a call costs exactly what the original costs.
 *
 * Calls out of a native (CALL in the original, the handler's CALL AX, and the tail JMPs to
 * switch_text, com_tune, nav_tune, text_07c5, obi_readout and cga_program_regs) run the target
 * the way the CPU would with the natives on: an enabled native at a reached address runs
 * through native_call() (the other entries of this file, draw_indicator, switch_text, ...),
 * anything else is single-stepped as original code. Interrupts are not delivered meanwhile.
 *
 * key_repeat_accel does not always return to its caller: when selected_item = 1 (after Scroll
 * Lock with the radar off) it picks a view direction, pops its return address and returns
 * from the key handler. call_rep() reports which way it went.
 *
 * Ctrl+Alt+Del (Delete with last_scancodes = 381Dh) makes key_dispatch jump to the BIOS reset
 * entry F000:E05B (pc.c traps it to a reboot). The native leaves CS:IP there and returns at
 * once; so does int9_keyboard.
 *
 * Interrupts (same scheme as 3.14 and 3.16). The handlers draw indicators through blit_or,
 * which executes STI, so the timer interrupt can arrive inside the keyboard interrupt; the
 * keyboard can also latch the next scancode meanwhile (kbd_poll after every instruction). A
 * native holds both until it returns. So a native that is not nested in another one runs with
 * an undo log; when the timer or the keyboard would have raised an interrupt within its
 * cycles, its memory writes are undone, the CPU and the device state (PIC, PIT, keyboard,
 * port 61h, speaker log) are restored, and the call is handed back to the original: its first
 * instruction is performed and the CPU continues in the original routine, with interrupts.
 * Under --verify (and nested in a native that keeps a log) they run plain. */
#include <SDL3/SDL.h>
#include <stddef.h>

#include "native.h"
#include "game/state.h"
#include "keys.h"
#include "keys_cycles.h"

/* ---- registers, memory ------------------------------------------------------------------ */

#define REG(r) (pc->cpu.regs[R_##r])
#define SREG(r) (pc->cpu.sregs[S_##r])
#define SET_LO(r, b) (REG(r) = (uint16_t)((REG(r) & 0xFF00) | (uint8_t)(b)))
#define SET_HI(r, b) (REG(r) = (uint16_t)((REG(r) & 0x00FF) | (uint16_t)((uint8_t)(b)) << 8))
#define AL ((uint8_t)REG(AX))
#define AH ((uint8_t)(REG(AX) >> 8))

#define rd8 gs_rd8
#define rd16 gs_rd16
#define wr8 gs_wr8
#define wr16 gs_wr16

static void port_out(Pc *pc, uint16_t port, uint8_t v) { pc->cpu.bus.out8(pc->cpu.bus.ctx, port, v); }
static uint8_t port_in(Pc *pc, uint16_t port) { return pc->cpu.bus.in8(pc->cpu.bus.ctx, port); }

/* ADD r/m16, imm and its overflow flag (for the JNO after it). */
static uint16_t add_of(uint16_t a, uint16_t b, bool *of)
{
    uint16_t r = (uint16_t)(a + b);
    *of = ((a ^ r) & (b ^ r) & 0x8000) != 0;
    return r;
}

/* SAR r/m8 by n. */
static uint8_t sar8(uint8_t v, int n) { return (uint8_t)((int8_t)v >> n); }

/* ---- cycles ---------------------------------------------------------------------------- */

#define N_COST (sizeof key_ins_cost / sizeof key_ins_cost[0])
#define ENTRY_CYCLES 1

static const KeyInsCost *ins_at(uint16_t addr)
{
    size_t lo = 0, hi = N_COST;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (key_ins_cost[mid].addr < addr)
            lo = mid + 1;
        else
            hi = mid;
    }
    return &key_ins_cost[lo];
}

/* The original executes every instruction in [from, to) in order (jumps fall through;
 * unconditional jumps cost what they cost). */
static void run(Pc *pc, uint16_t from, uint16_t to)
{
    for (const KeyInsCost *i = ins_at(from); i < key_ins_cost + N_COST && i->addr < to; i++)
        pc->cpu.cycles += i->cost;
}

/* The conditional jump at addr, already counted by run(), was taken. */
static void taken(Pc *pc, uint16_t addr)
{
    const KeyInsCost *i = ins_at(addr);
    pc->cpu.cycles += (uint64_t)i->taken - i->cost;
}

/* ---- calls ----------------------------------------------------------------------------- */

#define STEP_CAP 5000000L
#define RESET_CS 0xF000
#define RESET_IP 0xE05B

static bool at_reset(Pc *pc) { return SREG(CS) == RESET_CS && pc->cpu.ip == RESET_IP; }

/* Runs from 0050:target, as the CPU would with the natives on, until the routine returns
 * past the word on top of the stack (normally to it; key_repeat_accel returns one level
 * higher), or jumps to the reset entry (Ctrl+Alt+Del). */
static void run_from(Pc *pc, uint16_t target)
{
    Cpu8086 *c = &pc->cpu;
    uint16_t sp0 = c->regs[R_SP];
    const uint8_t *map = c->hook_map;
    c->sregs[S_CS] = GAME_CS;
    c->ip = target;
    for (long n = 0; n < STEP_CAP; n++) {
        bool done = false;
        if (map && c->sregs[S_CS] == GAME_CS && map[c->ip])
            done = native_call(pc, c->ip);
        if (!done) {
            c->hook_map = NULL; /* stepped here, so that no nested --verify starts */
            native_or_cpu_step(pc);
            c->hook_map = map;
        }
        uint16_t d = (uint16_t)(c->regs[R_SP] - sp0);
        if ((d >= 2 && d < 0x8000) || at_reset(pc))
            break;
    }
}

/* Performs the near CALL instruction at 0050:at (E8 rel16): its cost, the push, the callee.
 * Returns true when the callee came back to the instruction after the CALL. */
static bool call(Pc *pc, uint16_t at)
{
    uint16_t ret_ip = (uint16_t)(at + 3);
    uint16_t target = (uint16_t)(ret_ip + mem_read16(pc, GAME_CS, (uint16_t)(at + 1)));
    run(pc, at, ret_ip);
    cpu_push(&pc->cpu, ret_ip);
    run_from(pc, target);
    return pc->cpu.ip == ret_ip && SREG(CS) == GAME_CS;
}

/* JMP rel16 at 0050:at to a routine that returns to our caller (a tail call). */
static void tail(Pc *pc, uint16_t at)
{
    uint16_t target = (uint16_t)(at + 3 + mem_read16(pc, GAME_CS, (uint16_t)(at + 1)));
    run(pc, at, (uint16_t)(at + 3));
    run_from(pc, target);
}

/* RET at 0050:at. */
static void ret(Pc *pc, uint16_t at)
{
    run(pc, at, (uint16_t)(at + 1));
    native_ret(pc);
}

/* ---- interrupts ------------------------------------------------------------------------- */

/* --verify attaches its write log only while it runs a routine; in normal play it is NULL. */
static bool under_verify(Pc *pc) { return pc->cpu.write_log != NULL; }

/* True when the timer (PIT channel 0) or the keyboard would raise an interrupt within n
 * cycles of the call that started at cycle `start` (as in 3.14 and 3.16; the PIT is advanced
 * only after a native returns, so its state is still the one at the start). */
static bool irq_due(Pc *pc, uint64_t start, uint64_t n)
{
    if (pc->csched)
        return false; /* C scheduler (3.22): interrupts only come between natives */
    const PitChannel *t = &pc->pit[0];
    bool timer = pc->irq0_backlog || (t->loaded && t->count - (int64_t)((pc->pit_cycle_frac + n) / 4) <= 0);
    bool key = !pc->kbd_full && pc->kbd_head != pc->kbd_tail && start + n >= pc->kbd_next_cycle;
    return timer || key;
}

/* Device state the keyboard interrupt changes (port 60h read, port 61h pulse, EOI, the PIT
 * and vectors of key_enter): everything in Pc after mem/disk up to the speaker events, and
 * from speaker_count on (as native.c's --verify snapshot). */
#define DEV_A_START offsetof(Pc, pic_irr)
#define DEV_A_END offsetof(Pc, speaker)
#define DEV_B_START offsetof(Pc, speaker_count)
typedef struct DevState {
    uint8_t a[DEV_A_END - DEV_A_START];
    uint8_t b[sizeof(Pc) - DEV_B_START];
} DevState;

static void dev_save(const Pc *pc, DevState *d)
{
    SDL_memcpy(d->a, (const uint8_t *)pc + DEV_A_START, sizeof d->a);
    SDL_memcpy(d->b, (const uint8_t *)pc + DEV_B_START, sizeof d->b);
}

static void dev_load(Pc *pc, const DevState *d)
{
    SDL_memcpy((uint8_t *)pc + DEV_A_START, d->a, sizeof d->a);
    SDL_memcpy((uint8_t *)pc + DEV_B_START, d->b, sizeof d->b);
}

/* Hands the call back to the original: performs the routine's first instruction (natives
 * off), after which the CPU continues in the original routine, with interrupts. */
static void step_first(Pc *pc)
{
    Cpu8086 *c = &pc->cpu;
    const uint8_t *map = c->hook_map;
    c->hook_map = NULL;
    cpu_step(c);
    c->hook_map = map;
}

/* ---- 0050:0A0A-0A38 magnetos ---------------------------------------------------------- */

/* 0A19 magnetos_store: magnetos = AH, switch_text. */
static void b_magnetos_store(Pc *pc)
{
    run(pc, 0x0A19, 0x0A1D);
    gs_set_magnetos(pc, AH);
    call(pc, 0x0A1D); /* switch_text */
    ret(pc, 0x0A20);
}

/* 0A0D key_set_magnetos: AL bit 1 -> right switch, bit 0 -> left switch, AH -> magnetos. */
static void b_set_magnetos(Pc *pc)
{
    run(pc, 0x0A0D, 0x0A19);
    uint8_t al = AL;
    wr8(pc, (uint16_t)(GS_MAG_SWITCHES + 1), (uint8_t)(al >> 1));
    wr8(pc, GS_MAG_SWITCHES, (uint8_t)(al & 1));
    SET_LO(AX, al & 1);
    b_magnetos_store(pc);
}

static void mag_key(Pc *pc, uint16_t at, uint16_t ax)
{
    run(pc, at, (uint16_t)(at + 5));
    REG(AX) = ax;
    b_set_magnetos(pc);
}

static void b_key_mag_off(Pc *pc)
{
    run(pc, 0x0A0A, 0x0A0D);
    REG(AX) = 0;
    b_set_magnetos(pc);
}
static void b_key_mag_left(Pc *pc) { mag_key(pc, 0x0A21, 0x0102); }
static void b_key_mag_right(Pc *pc) { mag_key(pc, 0x0A26, 0x0201); }
static void b_key_mag_both(Pc *pc) { mag_key(pc, 0x0A2B, 0x0303); }
static void b_key_mag_start(Pc *pc) { mag_key(pc, 0x0A30, 0x0403); }
static void b_key_0(Pc *pc) { mag_key(pc, 0x0A35, 0x0500); }

/* ---- 0050:0A3A key_minus, 0B53 key_equals ---------------------------------------------- */

/* A transponder digit ('0'-'7'): mov al,[x] / cmp al,c / jne L1 / mov al,v / jmp S /
 * L1: dec|inc al / S: mov [x],al / jmp text_07c5. */
static void digit_step(Pc *pc, uint16_t e, uint16_t jne_at, uint16_t eqset, uint16_t l1, uint16_t store,
                       uint16_t end, uint16_t off, uint8_t cmpv, uint8_t setv, int delta)
{
    run(pc, e, eqset);
    uint8_t al = rd8(pc, off);
    if (al == cmpv) {
        run(pc, eqset, l1);
        al = setv;
    } else {
        taken(pc, jne_at);
        run(pc, l1, store);
        al = (uint8_t)(al + delta);
    }
    SET_LO(AX, al);
    run(pc, store, (uint16_t)(end - 3));
    wr8(pc, off, al);
    tail(pc, (uint16_t)(end - 3)); /* text_07c5 */
}

/* 0B91: store the COM MHz digits, tune. */
static void com_store_hi(Pc *pc)
{
    run(pc, 0x0B91, 0x0B96);
    wr16(pc, GS_COM_FREQ, REG(AX));
    tail(pc, 0x0BB8); /* com_tune */
}

static void com_store_lo(Pc *pc)
{
    run(pc, 0x0BB5, 0x0BB8);
    wr16(pc, (uint16_t)(GS_COM_FREQ + 5), REG(AX));
    tail(pc, 0x0BB8);
}

static void nav_store_hi(Pc *pc)
{
    run(pc, 0x0BD7, 0x0BDC);
    wr16(pc, GS_NAV_FREQ, REG(AX));
    tail(pc, 0x0BFE); /* nav_tune */
}

static void nav_store_lo(Pc *pc)
{
    run(pc, 0x0BFB, 0x0BFE);
    wr16(pc, (uint16_t)(GS_NAV_FREQ + 5), REG(AX));
    tail(pc, 0x0BFE);
}

/* Fractional digits ".00" -> ".95" -> ".90" ... (down) of COM (x = 07AB) or NAV (07B6). */
static void freq_lo_down(Pc *pc, uint16_t e, uint16_t off)
{
    /* e: mov ax,[x] / cmp ax,3030 / jne A / mov ax,3539 / jmp S
     * A (e+0D): cmp ah,30 / je B / mov ah,30 / jmp S / B (e+17): mov ah,35 / dec al / S */
    uint16_t a = (uint16_t)(e + 0x0D), b = (uint16_t)(e + 0x17), s = (uint16_t)(e + 0x1B);
    run(pc, e, (uint16_t)(e + 0x08));
    REG(AX) = rd16(pc, off);
    if (REG(AX) == 0x3030) {
        run(pc, (uint16_t)(e + 0x08), a);
        REG(AX) = 0x3539;
    } else {
        taken(pc, (uint16_t)(e + 0x06));
        run(pc, a, (uint16_t)(a + 5));
        if (AH == 0x30) {
            taken(pc, (uint16_t)(a + 3));
            run(pc, b, s);
            SET_HI(AX, 0x35);
            SET_LO(AX, AL - 1);
        } else {
            run(pc, (uint16_t)(a + 5), b);
            SET_HI(AX, 0x30);
        }
    }
    run(pc, s, (uint16_t)(s + 3)); /* jmp to the store */
}

static void b_key_minus(Pc *pc)
{
    run(pc, 0x0A3A, 0x0A49);
    uint8_t al = gs_selected_item(pc);
    gs_set_key_recent(pc, 0);
    bool zoom;
    if (gs_war_mode(pc) == 1) {
        taken(pc, 0x0A47);
        zoom = true;
    } else {
        run(pc, 0x0A49, 0x0A4D);
        al = (uint8_t)(al - 2);
        zoom = al == 0;
        if (!zoom)
            taken(pc, 0x0A4B);
    }
    SET_LO(AX, al);
    if (zoom) {
        run(pc, 0x0A4D, 0x0A5C);
        uint16_t lo = gs_rd16(pc, GS_RADAR_ZOOM), hi = gs_rd16(pc, (uint16_t)(GS_RADAR_ZOOM + 2));
        uint16_t nlo = (uint16_t)(lo << 1 | 1);
        uint16_t nhi = (uint16_t)(hi << 1 | lo >> 15);
        wr16(pc, GS_RADAR_ZOOM, nlo);
        wr16(pc, (uint16_t)(GS_RADAR_ZOOM + 2), nhi);
        wr16(pc, (uint16_t)(GS_RADAR_ZOOM + 2), (uint16_t)(nhi & 0x7FFF));
        ret(pc, 0x0A5C);
        return;
    }
    /* 0A5D: COM MHz */
    run(pc, 0x0A5D, 0x0A61);
    al = (uint8_t)(al - 2);
    SET_LO(AX, al);
    if (al == 0) {
        run(pc, 0x0A61, 0x0A69);
        REG(AX) = rd16(pc, GS_COM_FREQ);
        if (REG(AX) == 0x3831) {
            run(pc, 0x0A69, 0x0A6E);
            REG(AX) = 0x3533;
        } else {
            taken(pc, 0x0A67);
            run(pc, 0x0A6E, 0x0A75);
            SET_HI(AX, AH - 1);
            if (AH != 0x2F) {
                taken(pc, 0x0A73);
            } else {
                run(pc, 0x0A75, 0x0A79);
                SET_HI(AX, 0x39);
                SET_LO(AX, AL - 1);
            }
        }
        run(pc, 0x0A79, 0x0A7C);
        com_store_hi(pc);
        return;
    }
    taken(pc, 0x0A5F);
    /* 0A7C: COM fraction */
    run(pc, 0x0A7C, 0x0A80);
    SET_LO(AX, --al);
    if (al == 0) {
        freq_lo_down(pc, 0x0A80, (uint16_t)(GS_COM_FREQ + 5));
        com_store_lo(pc);
        return;
    }
    taken(pc, 0x0A7E);
    /* 0A9E: NAV MHz */
    run(pc, 0x0A9E, 0x0AA2);
    SET_LO(AX, --al);
    if (al == 0) {
        run(pc, 0x0AA2, 0x0AAA);
        REG(AX) = rd16(pc, GS_NAV_FREQ);
        if (REG(AX) == 0x3830) {
            run(pc, 0x0AAA, 0x0AAF);
            REG(AX) = 0x3731;
        } else {
            taken(pc, 0x0AA8);
            run(pc, 0x0AAF, 0x0AB6);
            SET_HI(AX, AH - 1);
            if (AH != 0x2F) {
                taken(pc, 0x0AB4);
            } else {
                run(pc, 0x0AB6, 0x0ABA);
                SET_HI(AX, 0x39);
                SET_LO(AX, AL - 1);
            }
        }
        run(pc, 0x0ABA, 0x0ABD);
        nav_store_hi(pc);
        return;
    }
    taken(pc, 0x0AA0);
    /* 0ABD: NAV fraction */
    run(pc, 0x0ABD, 0x0AC1);
    SET_LO(AX, --al);
    if (al == 0) {
        freq_lo_down(pc, 0x0AC1, (uint16_t)(GS_NAV_FREQ + 5));
        nav_store_lo(pc);
        return;
    }
    taken(pc, 0x0ABF);
    /* 0ADF..0B3B: transponder digits 1-4 */
    static const uint16_t tx[4][6] = {
        { 0x0ADF, 0x0AE3, 0x0AE8, 0x0AEA, 0x0AEE, 0x0AF0 },
        { 0x0AF6, 0x0AFA, 0x0AFF, 0x0B01, 0x0B05, 0x0B07 },
        { 0x0B0D, 0x0B11, 0x0B16, 0x0B18, 0x0B1C, 0x0B1E },
        { 0x0B24, 0x0B28, 0x0B2D, 0x0B2F, 0x0B33, 0x0B35 },
    };
    for (int i = 0; i < 4; i++) {
        run(pc, tx[i][0], tx[i][1]);
        SET_LO(AX, --al);
        if (al == 0) {
            digit_step(pc, tx[i][1], tx[i][2], tx[i][3], tx[i][4], tx[i][5], (uint16_t)(tx[i][5] + 6),
                       (uint16_t)(GS_TRANSPONDER + 1 + 2 * i), 0x30, 0x37, -1);
            return;
        }
        taken(pc, (uint16_t)(tx[i][0] + 2));
    }
    /* 0B3B: OBI course */
    run(pc, 0x0B3B, 0x0B3F);
    SET_LO(AX, --al);
    if (al != 0) {
        taken(pc, 0x0B3D);
        ret(pc, 0x0B52);
        return;
    }
    run(pc, 0x0B3F, 0x0B4A);
    uint8_t crs = (uint8_t)(rd8(pc, GS_OBI_COURSE) - 1);
    wr8(pc, GS_OBI_COURSE, crs);
    if (crs != 0xFF) {
        taken(pc, 0x0B48);
    } else {
        run(pc, 0x0B4A, 0x0B4F);
        wr8(pc, GS_OBI_COURSE, 0xB3);
    }
    tail(pc, 0x0B4F); /* obi_readout */
}

/* Fractional digits up: ".95" -> ".00", ".x0" -> ".x5", ".x5" -> ".(x+1)0". */
static void freq_lo_up(Pc *pc, uint16_t e, uint16_t off, bool nop_after_eq)
{
    /* e: mov ax,[x] / cmp ax,3539 / jne A / mov ax,3030 / jmp S [/ nop]
     * A: cmp ah,35 / je B / mov ah,35 / jmp S / B: mov ah,30 / inc al / S */
    uint16_t a = (uint16_t)(e + (nop_after_eq ? 0x0E : 0x0D));
    uint16_t b = (uint16_t)(a + 9), s = (uint16_t)(b + 4);
    run(pc, e, (uint16_t)(e + 0x08));
    REG(AX) = rd16(pc, off);
    if (REG(AX) == 0x3539) {
        run(pc, (uint16_t)(e + 0x08), a);
        REG(AX) = 0x3030;
    } else {
        taken(pc, (uint16_t)(e + 0x06));
        run(pc, a, (uint16_t)(a + 5));
        if (AH == 0x35) {
            taken(pc, (uint16_t)(a + 3));
            run(pc, b, s);
            SET_HI(AX, 0x30);
            SET_LO(AX, AL + 1);
        } else {
            run(pc, (uint16_t)(a + 5), b);
            SET_HI(AX, 0x35);
        }
    }
}

static void b_key_equals(Pc *pc)
{
    run(pc, 0x0B53, 0x0B62);
    uint8_t al = gs_selected_item(pc);
    gs_set_key_recent(pc, 0);
    bool zoom;
    if (gs_war_mode(pc) == 1) {
        taken(pc, 0x0B60);
        zoom = true;
    } else {
        run(pc, 0x0B62, 0x0B66);
        al = (uint8_t)(al - 2);
        zoom = al == 0;
        if (!zoom)
            taken(pc, 0x0B64);
    }
    SET_LO(AX, al);
    if (zoom) {
        run(pc, 0x0B66, 0x0B74);
        uint16_t lo = gs_rd16(pc, GS_RADAR_ZOOM), hi = gs_rd16(pc, (uint16_t)(GS_RADAR_ZOOM + 2));
        uint16_t nhi = (uint16_t)((int16_t)hi >> 1);
        uint16_t nlo = (uint16_t)(lo >> 1 | (hi & 1) << 15);
        wr16(pc, (uint16_t)(GS_RADAR_ZOOM + 2), nhi);
        wr16(pc, GS_RADAR_ZOOM, nlo);
        wr16(pc, GS_RADAR_ZOOM, (uint16_t)(nlo | 0x1FFF));
        ret(pc, 0x0B74);
        return;
    }
    /* 0B75: COM MHz */
    run(pc, 0x0B75, 0x0B79);
    al = (uint8_t)(al - 2);
    SET_LO(AX, al);
    if (al == 0) {
        run(pc, 0x0B79, 0x0B81);
        REG(AX) = rd16(pc, GS_COM_FREQ);
        if (REG(AX) == 0x3533) {
            run(pc, 0x0B81, 0x0B86);
            REG(AX) = 0x3831;
        } else {
            taken(pc, 0x0B7F);
            run(pc, 0x0B86, 0x0B8D);
            SET_HI(AX, AH + 1);
            if (AH != 0x3A) {
                taken(pc, 0x0B8B);
            } else {
                run(pc, 0x0B8D, 0x0B91);
                SET_HI(AX, 0x30);
                SET_LO(AX, AL + 1);
            }
        }
        com_store_hi(pc);
        return;
    }
    taken(pc, 0x0B77);
    /* 0B97: COM fraction */
    run(pc, 0x0B97, 0x0B9B);
    SET_LO(AX, --al);
    if (al == 0) {
        freq_lo_up(pc, 0x0B9B, (uint16_t)(GS_COM_FREQ + 5), false);
        com_store_lo(pc);
        return;
    }
    taken(pc, 0x0B99);
    /* 0BBB: NAV MHz */
    run(pc, 0x0BBB, 0x0BBF);
    SET_LO(AX, --al);
    if (al == 0) {
        run(pc, 0x0BBF, 0x0BC7);
        REG(AX) = rd16(pc, GS_NAV_FREQ);
        if (REG(AX) == 0x3731) {
            run(pc, 0x0BC7, 0x0BCC);
            REG(AX) = 0x3830;
        } else {
            taken(pc, 0x0BC5);
            run(pc, 0x0BCC, 0x0BD3);
            SET_HI(AX, AH + 1);
            if (AH != 0x3A) {
                taken(pc, 0x0BD1);
            } else {
                run(pc, 0x0BD3, 0x0BD7);
                SET_HI(AX, 0x30);
                SET_LO(AX, AL + 1);
            }
        }
        nav_store_hi(pc);
        return;
    }
    taken(pc, 0x0BBD);
    /* 0BDC: NAV fraction */
    run(pc, 0x0BDC, 0x0BE0);
    SET_LO(AX, --al);
    if (al == 0) {
        freq_lo_up(pc, 0x0BE0, (uint16_t)(GS_NAV_FREQ + 5), true);
        nav_store_lo(pc);
        return;
    }
    taken(pc, 0x0BDE);
    /* 0C01..0C61: transponder digits 1-4 */
    static const uint16_t tx[4][6] = {
        { 0x0C01, 0x0C05, 0x0C0A, 0x0C0C, 0x0C11, 0x0C13 },
        { 0x0C19, 0x0C1D, 0x0C22, 0x0C24, 0x0C29, 0x0C2B },
        { 0x0C31, 0x0C35, 0x0C3A, 0x0C3C, 0x0C41, 0x0C43 },
        { 0x0C49, 0x0C4D, 0x0C52, 0x0C54, 0x0C59, 0x0C5B },
    };
    for (int i = 0; i < 4; i++) {
        run(pc, tx[i][0], tx[i][1]);
        SET_LO(AX, --al);
        if (al == 0) {
            digit_step(pc, tx[i][1], tx[i][2], tx[i][3], tx[i][4], tx[i][5], (uint16_t)(tx[i][5] + 6),
                       (uint16_t)(GS_TRANSPONDER + 1 + 2 * i), 0x37, 0x30, +1);
            return;
        }
        taken(pc, (uint16_t)(tx[i][0] + 2));
    }
    /* 0C61: OBI course */
    run(pc, 0x0C61, 0x0C65);
    SET_LO(AX, --al);
    if (al != 0) {
        taken(pc, 0x0C63);
        ret(pc, 0x0C78);
        return;
    }
    run(pc, 0x0C65, 0x0C70);
    uint8_t crs = (uint8_t)(rd8(pc, GS_OBI_COURSE) + 1);
    wr8(pc, GS_OBI_COURSE, crs);
    if (crs != 0xB4) {
        taken(pc, 0x0C6E);
    } else {
        run(pc, 0x0C70, 0x0C75);
        wr8(pc, GS_OBI_COURSE, 0);
    }
    tail(pc, 0x0C75); /* obi_readout */
}

