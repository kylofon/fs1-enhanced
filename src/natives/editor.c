    REG(AX) = (uint16_t)v;
    REG(DX) = (uint16_t)((v >> 16) - 9);
    gs_set_editor_alt(pc, REG(DX));
    run(pc, 0x3AB4, 0x3AC8);
    REG(CX) = 0x168;
