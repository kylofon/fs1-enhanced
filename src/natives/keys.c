/* 0050:109B key_repeat_accel: BL = keypad key index. With selected_item = 1 it takes the
 * key as a view direction and returns from the key handler (pops the return address). */
static void b_key_repeat_accel(Pc *pc)
{
    run(pc, 0x109B, 0x10A2);
    if (gs_selected_item(pc) != 1) {
        ret(pc, 0x10A2);
        return;
    }
    taken(pc, 0x10A0);
    run(pc, 0x10A3, 0x10B5);
    gs_set_selected_item(pc, 0);
    REG(BX) &= 0x00FF;
    REG(AX) = rd16(pc, (uint16_t)(GS_VIEW_DIR_FNS + REG(BX)));
    gs_set_view_dir_fn(pc, REG(AX));
    wr16(pc, GS_VIEW_NOT_FORWARD, REG(BX));
    REG(AX) = cpu_pop(&pc->cpu);
    ret(pc, 0x10B5);
}

/* mov bl,idx / call key_repeat_accel at `at`. False: it returned from the key handler. */
