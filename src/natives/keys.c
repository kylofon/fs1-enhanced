/* C and N: select the radio; again within key_recent frames: its second field. */
static void select_radio(Pc *pc, uint16_t e, uint8_t item)
{
    /* e: [mov com_search,1 /] cmp key_recent,0 / je L / cmp sel,item / jne L / inc sel / ret
     * L: mov sel,item / mov key_recent,12h / ret */
    uint16_t c1 = e, l = (uint16_t)(e + 0x13);
    run(pc, c1, (uint16_t)(c1 + 7));
    if (gs_key_recent(pc) == 0) {
        taken(pc, (uint16_t)(c1 + 5));
    } else {
        run(pc, (uint16_t)(c1 + 7), (uint16_t)(c1 + 0x0E));
        if (gs_selected_item(pc) != item) {
            taken(pc, (uint16_t)(c1 + 0x0C));
        } else {
            run(pc, (uint16_t)(c1 + 0x0E), (uint16_t)(c1 + 0x12));
            gs_set_selected_item(pc, (uint8_t)(item + 1));
            ret(pc, (uint16_t)(c1 + 0x12));
            return;
        }
    }
    run(pc, l, (uint16_t)(l + 0x0A));
    gs_set_selected_item(pc, item);
    gs_set_key_recent(pc, 0x12);
    ret(pc, (uint16_t)(l + 0x0A));
}

