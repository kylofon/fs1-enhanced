/* ---- registers, memory ------------------------------------------------------------------ */

#define REG(r) (pc->cpu.regs[R_##r])
#define SREG(r) (pc->cpu.sregs[S_##r])
#define SET_LO(r, b) (REG(r) = (uint16_t)((REG(r) & 0xFF00) | (uint8_t)(b)))
#define SET_HI(r, b) (REG(r) = (uint16_t)((REG(r) & 0x00FF) | (uint16_t)((uint8_t)(b)) << 8))
#define AL ((uint8_t)REG(AX))

/* DS-relative with the live DS (the generated accessors' gs_rd* / gs_wr*). */
#define rd8 gs_rd8
#define rd16 gs_rd16
#define wr8 gs_wr8
#define wr16 gs_wr16
static uint8_t erd8(Pc *pc, uint16_t off) { return cpu_read8(&pc->cpu, cpu_linear(SREG(ES), off)); }
static void ewr8(Pc *pc, uint16_t off, uint8_t v) { cpu_write8(&pc->cpu, cpu_linear(SREG(ES), off), v); }

static int dstep(Pc *pc, int size) { return (pc->cpu.flags & F_DF) ? -size : size; }

static void port_out(Pc *pc, uint16_t port, uint8_t v) { pc->cpu.bus.out8(pc->cpu.bus.ctx, port, v); }
static uint8_t port_in(Pc *pc, uint16_t port) { return pc->cpu.bus.in8(pc->cpu.bus.ctx, port); }

/* MUL r/m16: DX:AX = AX * v. */
static void mul16(Pc *pc, uint16_t v)
{
    uint32_t p = (uint32_t)REG(AX) * v;
    REG(AX) = (uint16_t)p;
    REG(DX) = (uint16_t)(p >> 16);
}

/* "mov al,ah; mov ah,dl" after a MUL: the middle 16 bits of DX:AX. */
static void mid16(Pc *pc) { REG(AX) = (uint16_t)((REG(DX) & 0xFF) << 8 | REG(AX) >> 8); }

/* ---- cycles ---------------------------------------------------------------------------- */

#define N_COST (sizeof ed_ins_cost / sizeof ed_ins_cost[0])
#define ENTRY_CYCLES 1

static const EdInsCost *ins_at(uint16_t addr)
{
    size_t lo = 0, hi = N_COST;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (ed_ins_cost[mid].addr < addr)
            lo = mid + 1;
        else
            hi = mid;
    }
    return &ed_ins_cost[lo];
}

/* The original executes every instruction in [from, to) in order (jumps fall through). */
static void run(Pc *pc, uint16_t from, uint16_t to)
{
    for (const EdInsCost *i = ins_at(from); i < ed_ins_cost + N_COST && i->addr < to; i++)
        pc->cpu.cycles += i->cost;
}

/* The conditional jump (or LOOP) at addr, already counted by run(), was taken. */
static void taken(Pc *pc, uint16_t addr)
{
    const EdInsCost *i = ins_at(addr);
    pc->cpu.cycles += (uint64_t)i->taken - i->cost;
}

/* ---- calls ----------------------------------------------------------------------------- */

#define STEP_CAP 5000000L

/* Runs from 0050:target until the routine returns to the address on top of the stack, as
 * the CPU would with the natives on (see the top of the file). */
static void run_from(Pc *pc, uint16_t target)
{
    Cpu8086 *c = &pc->cpu;
    uint16_t sp0 = c->regs[R_SP];
    uint16_t ret_ip = mem_read16(pc, c->sregs[S_SS], sp0);
    const uint8_t *map = c->hook_map;
    c->sregs[S_CS] = GAME_CS;
    c->ip = target;
    for (long n = 0; n < STEP_CAP; n++) {
        bool done = false;
        if (map && c->sregs[S_CS] == GAME_CS && map[c->ip])
            done = native_call(pc, c->ip);
        if (!done) {
            c->hook_map = NULL; /* stepped here, so that no nested --verify starts */
            native_or_cpu_step(pc);
            c->hook_map = map;
        }
        uint16_t d = (uint16_t)(c->regs[R_SP] - sp0);
        if (c->ip == ret_ip && c->sregs[S_CS] == GAME_CS && d >= 2 && d < 0x8000)
            break;
    }
}

/* Performs the near CALL instruction at 0050:at (E8 rel16): its cost, the push, the callee. */
static void call(Pc *pc, uint16_t at)
{
    uint16_t ret_ip = (uint16_t)(at + 3);
    uint16_t target = (uint16_t)(ret_ip + mem_read16(pc, GAME_CS, (uint16_t)(at + 1)));
    run(pc, at, ret_ip);
    cpu_push(&pc->cpu, ret_ip);
    run_from(pc, target);
}

/* RET at 0050:at. */
static void ret(Pc *pc, uint16_t at)
{
    run(pc, at, (uint16_t)(at + 1));
    native_ret(pc);
}

/* Single-steps original code (natives off) from 0050:from until IP = until with SP = sp.
 * Used for the divide-error path (DIV overflow -> INT 0 -> IRET to the next instruction). */
static void step_original(Pc *pc, uint16_t from, uint16_t until)
{
    Cpu8086 *c = &pc->cpu;
    const uint8_t *map = c->hook_map;
    uint16_t sp = c->regs[R_SP];
    c->hook_map = NULL;
    c->ip = from;
    for (long n = 0; n < STEP_CAP; n++) {
        native_or_cpu_step(pc);
        if (c->ip == until && c->sregs[S_CS] == GAME_CS && c->regs[R_SP] == sp)
            break;
    }
    c->hook_map = map;
}

/* ---- interrupts ------------------------------------------------------------------------- */

/* --verify attaches its write log only while it runs a routine; in normal play it is NULL. */
static bool under_verify(Pc *pc) { return pc->cpu.write_log != NULL; }

/* True when the timer (PIT channel 0) or the keyboard would raise an interrupt within n
 * cycles of the call that started at cycle `start` (the test of 3.14's irq_hand_back; the PIT
 * is advanced only after a native returns, so its state is still the one at the start). */
static bool irq_due(Pc *pc, uint64_t start, uint64_t n)
{
    if (pc->csched)
        return false; /* C scheduler (3.22): interrupts only come between natives */
    const PitChannel *t = &pc->pit[0];
    bool timer = pc->irq0_backlog || (t->loaded && t->count - (int64_t)((pc->pit_cycle_frac + n) / 4) <= 0);
    bool key = !pc->kbd_full && pc->kbd_head != pc->kbd_tail && start + n >= pc->kbd_next_cycle;
    return timer || key;
}

/* Hands the call back to the original: performs the routine's first instruction (natives
 * off), after which the CPU continues in the original routine, with interrupts. */
static void step_first(Pc *pc)
{
    Cpu8086 *c = &pc->cpu;
    const uint8_t *map = c->hook_map;
    c->hook_map = NULL;
    cpu_step(c);
    c->hook_map = map;
}

