/* FS1_KEYS_CYCLE_CHECK=1 (debugging aid): before each call that is not nested in a native,
 * the original routine is single-stepped with a write log (other natives running as they
 * do), undone, and its cycles are compared with the native's. Hand-back is off meanwhile. */
static int cycle_check = -1;
static CpuWriteLog check_log, irq_log;

static bool log_ready(CpuWriteLog *l)
{
    if (!l->addr) {
        l->cap = 1u << 20;
        l->addr = SDL_malloc(l->cap * sizeof *l->addr);
        l->old = SDL_malloc(l->cap);
        if (!l->addr || !l->old) {
            SDL_free(l->addr);
            SDL_free(l->old);
            l->addr = NULL;
            l->old = NULL;
            return false;
        }
    }
    l->count = 0;
    l->overflow = false;
    return true;
}

static DevState dev_pre;

static bool check_original(Pc *pc, bool iret, uint64_t *cycles)
{
    Cpu8086 *c = &pc->cpu;
    if (!log_ready(&check_log))
        return false;
    Cpu8086 pre = *c;
    dev_save(pc, &dev_pre);
    uint16_t sp0 = c->regs[R_SP];
    uint16_t ret_ip = mem_read16(pc, c->sregs[S_SS], sp0);
    uint16_t ret_cs = iret ? mem_read16(pc, c->sregs[S_SS], (uint16_t)(sp0 + 2)) : GAME_CS;
    c->write_log = &check_log;
    const uint8_t *map = c->hook_map;
    bool returned = false;
    for (long n = 0; n < STEP_CAP && !returned; n++) {
        if (!(n && map && c->sregs[S_CS] == GAME_CS && map[c->ip] && native_call(pc, c->ip))) {
            c->hook_map = NULL;
            native_or_cpu_step(pc);
            c->hook_map = map;
        }
        uint16_t d = (uint16_t)(c->regs[R_SP] - sp0);
        returned = (c->ip == ret_ip && c->sregs[S_CS] == ret_cs && d >= 2 && d < 0x8000) || at_reset(pc);
    }
    *cycles = c->cycles - pre.cycles;
    for (uint32_t i = check_log.count; i-- > 0;)
        pc->mem[check_log.addr[i]] = check_log.old[i];
    bool ok = returned && !check_log.overflow && !at_reset(pc);
    *c = pre;
    dev_load(pc, &dev_pre);
    return ok;
}

static void entry_run(Pc *pc, const char *name, void (*body)(Pc *), bool iret)
{
    Cpu8086 *c = &pc->cpu;
    if (cycle_check < 0)
        cycle_check = SDL_getenv("FS1_KEYS_CYCLE_CHECK") != NULL;
    uint64_t start = c->cycles;
    if (under_verify(pc)) {
        /* --verify, or nested in a native that keeps a log */
        body(pc);
    } else if (cycle_check) {
        uint64_t orig = 0;
        bool check = check_original(pc, iret, &orig);
        if (check && log_ready(&check_log))
            c->write_log = &check_log; /* nested natives run plain */
        body(pc);
        c->write_log = NULL;
        if (check && c->cycles - start != orig)
            SDL_Log("cycle-check %s: original %llu native %llu", name, (unsigned long long)orig,
                    (unsigned long long)(c->cycles - start));
    } else if (!pc->csched && log_ready(&irq_log)) {
        Cpu8086 pre = *c;
        dev_save(pc, &dev_pre);
        c->write_log = &irq_log;
        body(pc);
        c->write_log = NULL;
        if (!irq_log.overflow && irq_due(pc, start, c->cycles - start)) {
            for (uint32_t i = irq_log.count; i-- > 0;)
                pc->mem[irq_log.addr[i]] = irq_log.old[i];
            *c = pre;
            dev_load(pc, &dev_pre);
            step_first(pc);
        }
    } else {
        body(pc);
    }
    c->cycles -= ENTRY_CYCLES;
}

