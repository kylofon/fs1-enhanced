/* ---- 0050:379A / 37B5: 's' / 'l', presets to / from a host file ------------------------------ */

#define PRESET_FILE "fs1_presets.bin"
#define PRESET_BYTES (0x30B4 - GS_USERMODE_SLOTS) /* 79Eh: 30 slots of 41h bytes */
#define TRACK_PRESETS 0x26
#define SCREEN_SEG 0xB800

/* The preset file: $FS1_PRESETS if set; else fs1_presets.bin next to the executable
 * (SDL_GetBasePath), or in the user's preference folder (SDL_GetPrefPath) when the
 * executable's folder is not writable (saving) or has no file (loading). Returns an
 * SDL_malloc'ed path, or NULL. */
static char *preset_path(bool pref)
{
    const char *env = SDL_getenv("FS1_PRESETS");
    char *path = NULL;
    if (env && *env)
        return pref ? NULL : SDL_strdup(env);
    if (!pref) {
        const char *base = SDL_GetBasePath();
        if (base)
            SDL_asprintf(&path, "%s%s", base, PRESET_FILE);
    } else {
        char *dir = SDL_GetPrefPath("fs1-sdl3", "Flight Simulator 1");
        if (dir)
            SDL_asprintf(&path, "%s%s", dir, PRESET_FILE);
        SDL_free(dir);
    }
    return path;
}

static bool preset_write(const uint8_t *data)
{
    for (int pref = 0; pref < 2; pref++) {
        char *path = preset_path(pref);
        if (!path)
            continue;
        bool ok = SDL_SaveFile(path, data, PRESET_BYTES);
        if (ok)
            SDL_Log("editor: presets saved to %s", path);
        SDL_free(path);
        if (ok)
            return true;
    }
    SDL_Log("editor: presets not saved: %s", SDL_GetError());
    return false;
}

/* Reads the preset file into data; false if there is none (or it has the wrong size). */
static bool preset_read(uint8_t *data)
{
    for (int pref = 0; pref < 2; pref++) {
        char *path = preset_path(pref);
        if (!path)
            continue;
        size_t size = 0;
        void *buf = SDL_LoadFile(path, &size);
        if (buf && size == PRESET_BYTES) {
            SDL_memcpy(data, buf, PRESET_BYTES);
            SDL_Log("editor: presets loaded from %s", path);
            SDL_free(buf);
            SDL_free(path);
            return true;
        }
        if (buf)
            SDL_Log("editor: %s has %u bytes, not %u; ignored", path, (unsigned)size, (unsigned)PRESET_BYTES);
        SDL_free(buf);
        SDL_free(path);
    }
    return false;
}

/* The cycles of the original's disk code that the natives replace, on the paths a good
 * write, a good read and a failed read take, so that the timeline stays the original's. An
 * INT 13h costs its INT (in the table) plus the BIOS stub "0F nn" and IRET. */
#define INT13_STUB_CYCLES (2 + 34)

static void cost_disk_ds(Pc *pc) { run(pc, 0x00F8, 0x0104); } /* sub_00F8 */

static void cost_checksum(Pc *pc) /* track_checksum 0157: 800h words */
{
    run(pc, 0x0157, 0x0161);
    for (int i = 0; i < 0x800; i++) {
        run(pc, 0x0161, 0x0169);
        if (i + 1 < 0x800)
            taken(pc, 0x0167);
    }
    run(pc, 0x0169, 0x016B);
}

/* sub_01DE: disk_format_write_track (format, write, read back, compare), stream_pos = FFFF */
static void cost_track_write(Pc *pc)
{
    run(pc, 0x01DE, 0x01E1);
    run(pc, 0x00BE, 0x00C1);
    cost_disk_ds(pc);
    run(pc, 0x00C1, 0x00C7);
    for (int i = 0; i < 8; i++) {
        run(pc, 0x00C7, 0x00D0);
        if (i < 7)
            taken(pc, 0x00CE);
    }
    run(pc, 0x00D0, 0x00EA);
    pc->cpu.cycles += INT13_STUB_CYCLES;
    taken(pc, 0x00E8);
    run(pc, 0x0109, 0x0137);
    pc->cpu.cycles += INT13_STUB_CYCLES;
    run(pc, 0x0137, 0x0142);
    cost_checksum(pc);
    run(pc, 0x0142, 0x0148);
    pc->cpu.cycles += INT13_STUB_CYCLES;
    run(pc, 0x0148, 0x014E);
    cost_checksum(pc);
    run(pc, 0x014E, 0x0157);
    run(pc, 0x01E1, 0x01E8);
}

/* the first boot_stream_byte of a load: boot_read_track, good or failed, then the byte */
static void cost_first_read(Pc *pc, bool ok)
{
    run(pc, 0x017C, 0x0187);
    taken(pc, 0x0185);
    run(pc, 0x0195, 0x019A);
    run(pc, 0x0104, 0x0107);
    cost_disk_ds(pc);
    run(pc, 0x0107, 0x0137);
    pc->cpu.cycles += INT13_STUB_CYCLES;
    if (ok) {
        run(pc, 0x0137, 0x013F);
        taken(pc, 0x013D);
        run(pc, 0x0152, 0x0157);
    } else {
        run(pc, 0x0137, 0x0139);
        taken(pc, 0x0137);
        run(pc, 0x00EA, 0x00F0);
    }
    run(pc, 0x019A, 0x01A0);
    run(pc, 0x0187, 0x0195);
}

/* 37C9: pop ax; call 016B (drive motor off); jmp 3643 (redraw, key loop). */
static void preset_tail(Pc *pc)
{
    run(pc, 0x37C9, 0x37CA);
    REG(AX) = cpu_pop(&pc->cpu);
    call(pc, 0x37CA);
    run(pc, 0x37CD, 0x37D0);
    pc->cpu.ip = 0x3643;
}

/* 379A: entered with CX = 79Eh, SI = 2916h. The original copies the presets through the
 * stream buffer (B800:0000, put_byte) and writes them to track 26h (format, write, read back,
 * checksum). The native writes the host file and leaves memory as the original's successful
 * write does: B800:0000..079D = presets, stream_pos = FFFF, disk_track = 27h, format_table
 * tracks = 26h, track_verify = 0, disk_dx = 0. */
static void b_preset_save(Pc *pc)
{
    call(pc, 0x379A); /* cga_program_regs */
    call(pc, 0x379D); /* disk_reset: DS = ES = [0000:0120] */
    run(pc, 0x37A0, 0x37A6);
    uint8_t data[PRESET_BYTES];
    for (unsigned i = 0; i < PRESET_BYTES; i++) {
        data[i] = rd8(pc, (uint16_t)(REG(SI) + i));
        cpu_write8(&pc->cpu, cpu_linear(SCREEN_SEG, (uint16_t)i), data[i]);
        run(pc, 0x37A6, 0x37AC);
        run(pc, 0x01AD, 0x01C6);
        if (i + 1 < PRESET_BYTES)
            taken(pc, 0x37AA);
    }
    SET_LO(AX, data[PRESET_BYTES - 1]);
    REG(SI) = (uint16_t)(REG(SI) + PRESET_BYTES);
    REG(CX) = 0;
    REG(DI) = SCREEN_SEG;
    preset_write(data);
    /* sub_01DE / disk_format_write_track, as after a successful write */
    run(pc, 0x37AC, 0x37AF);
    cost_track_write(pc);
    for (int k = 0; k < 8; k++)
        gs_set_format_table_b(pc, 4u * k, TRACK_PRESETS);
    gs_set_track_verify(pc, 0);
    gs_set_screen_seg(pc, SCREEN_SEG);
    gs_set_disk_dx(pc, 0);
    gs_set_disk_track(pc, TRACK_PRESETS + 1);
    gs_set_stream_pos(pc, 0xFFFF);
    REG(BX) = 0;
    REG(DX) = 0;
    SREG(ES) = SCREEN_SEG;
    run(pc, 0x37AF, 0x37B1);
    preset_tail(pc);
}

/* 37B5: entered with CX = 79Eh, SI = 2916h. The original streams track 26h through
 * boot_stream_byte into the presets. With a preset file, memory ends as after a good read:
 * B800:0000..079D = file, presets = file, disk_track = 27h. Without one it ends as the
 * original with an unformatted track: the read fails (disk_error = 1, disk_track stays 26h)
 * and the presets get whatever is in the track buffer B800:0000..079D, which is the editor's
 * text screen (characters and attribute bytes 0Fh). */
static void b_preset_load(Pc *pc)
{
    call(pc, 0x37B5); /* cga_program_regs */
    call(pc, 0x37B8); /* disk_reset */
    run(pc, 0x37BB, 0x37C3);
    REG(DI) = REG(SI);
    uint8_t data[PRESET_BYTES];
    bool ok = preset_read(data);
    gs_set_track_verify(pc, 0);
    gs_set_screen_seg(pc, SCREEN_SEG);
    gs_set_disk_dx(pc, 0);
    if (ok) {
        gs_set_disk_track(pc, TRACK_PRESETS + 1);
        for (unsigned i = 0; i < PRESET_BYTES; i++)
            cpu_write8(&pc->cpu, cpu_linear(SCREEN_SEG, (uint16_t)i), data[i]);
    } else {
        SDL_Log("editor: no preset file; loading as from an unformatted track");
        gs_set_disk_error(pc, 1);
        for (unsigned i = 0; i < PRESET_BYTES; i++)
            data[i] = cpu_read8(&pc->cpu, cpu_linear(SCREEN_SEG, (uint16_t)i));
    }
    for (unsigned i = 0; i < PRESET_BYTES; i++) {
        cpu_write8(&pc->cpu, cpu_linear(SREG(ES), REG(DI)), data[i]);
        REG(DI) = (uint16_t)(REG(DI) + dstep(pc, 1));
        run(pc, 0x37C3, 0x37C9);
        if (i == 0)
            cost_first_read(pc, ok);
        else
            run(pc, 0x017C, 0x0195);
        if (i + 1 < PRESET_BYTES)
            taken(pc, 0x37C7);
    }
    gs_set_stream_pos(pc, PRESET_BYTES - 1);
    REG(BX) = PRESET_BYTES - 1;
    SET_LO(AX, data[PRESET_BYTES - 1]);
    REG(CX) = 0;
    preset_tail(pc);
}

