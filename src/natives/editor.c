/* ---- 0050:629C check_master_disk (start-up) ----------------------------------------------- */

/* 60F8: disk_reset; CL = 0; SI = DI = 40B0h + DS * 16; ES = AX = 0. */
static void b_startup_disk_reset(Pc *pc)
{
    call(pc, 0x60F8);
    run(pc, 0x60FB, 0x6112);
    SET_LO(CX, 0);
    REG(SI) = (uint16_t)(0x40B0 + (uint16_t)(SREG(DS) << 4));
    REG(AX) = 0;
    SREG(ES) = 0;
    REG(DI) = REG(SI);
    ret(pc, 0x6112);
}

/* Up to 5 tries to read byte 0 of track 1Ch: 1 = master (CF = 1), 2 = copy (CF = 0). After
 * 5 failures (with backup_option != 1) the original shows an error and halts at 6311; the
 * native continues there in the original (no RET). */
static void b_check_master_disk(Pc *pc)
{
    run(pc, 0x629C, 0x629F);
    REG(CX) = 5;
    for (;;) {
        run(pc, 0x629F, 0x62A0);
        cpu_push(&pc->cpu, REG(CX));
        run(pc, 0x62A0, 0x62A3);
        cpu_push(&pc->cpu, 0x62A3);
        b_startup_disk_reset(pc);
        run(pc, 0x62A3, 0x62AE);
        gs_set_disk_track(pc, 0x1C);
        gs_set_stream_pos(pc, 0x0FFF);
        call(pc, 0x62AE); /* boot_stream_byte */
        run(pc, 0x62B1, 0x62B8);
        REG(CX) = cpu_pop(&pc->cpu);
        uint8_t e = gs_disk_error(pc);
        gs_set_disk_error(pc, (uint8_t)(e >> 1));
        bool retry = true;
        if (!(e & 1)) {
            taken(pc, 0x62B6);
            run(pc, 0x62C4, 0x62C8);
            if (AL == 1) {
                taken(pc, 0x62C6);
                run(pc, 0x62CE, 0x62CF);
                pc->cpu.flags |= F_CF;
                ret(pc, 0x62CF);
                return;
            }
            run(pc, 0x62C8, 0x62CC);
            if (AL == 2) {
                taken(pc, 0x62CA);
                retry = false;
            } else {
                run(pc, 0x62CC, 0x62CE);
                taken(pc, 0x62CC);
            }
        }
        if (retry) {
            run(pc, 0x62B8, 0x62BF);
            if (gs_backup_option(pc) == 1) {
                taken(pc, 0x62BD);
                retry = false;
            }
        }
        if (retry) {
            run(pc, 0x62BF, 0x62C2);
            if (--REG(CX) != 0) {
                taken(pc, 0x62C0);
                continue;
            }
            run(pc, 0x62C2, 0x62C4);
            pc->cpu.ip = 0x6311; /* error message, then JMP $ */
            return;
        }
        run(pc, 0x62D0, 0x62D1);
        pc->cpu.flags &= (uint16_t)~F_CF;
        ret(pc, 0x62D1);
        return;
    }
}

