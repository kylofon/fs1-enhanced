/* Natives for subphase 3.19 sound (see docs/PHASE3_PLAN.md and docs/subphases/3.19.md): the
 * timer interrupt int8_timer (0050:07A0), sound_update (087F, its table handlers and the PIT
 * channel 0 programming at 0922) and speaker_tone (0944). speaker_off (3B29) is a 3.16 native
 * (editor.c) and is called from here.
 *
 * The emulated sound path stays: these routines write ports 40h, 42h and 61h through the CPU
 * bus (pc->cpu.bus.out8), so pc.c's PIT, port 61h and speaker event log see every write.
 *
 * As in 3.16 and 3.18 (editor.c, keys.c), the routines are transliterated on the emulated
 * registers, so every register, segment register and memory byte (stack words written by CALL
 * and PUSH included) ends as the original leaves it; flags are not kept (sound_update and
 * speaker_* callers do not read them; int8_timer's IRET restores them). Memory goes through
 * the generated accessors of game/state.h, on the live DS.
 *
 * Cycles: run(from, to) adds the cpu8086.c cost of every original instruction in [from, to)
 * (table sound_cycles.h, generated by tools/gen_sound_cycles.py), taken() the extra cost of a
 * conditional jump that was taken. Every entry's .cycles is ENTRY_CYCLES and is subtracted
 * again, so a call costs exactly what the original costs.
 *
 * Port timing. The clock is advanced instruction by instruction before each IN/OUT, and an
 * OUT is performed 2 cycles into its instruction, where cpu8086.c performs it; so the
 * speaker events get the same cycle stamps as with the original. Before a write to a PIT
 * port the native calls pc_sync_pit() (3.21) at the OUT instruction's start: pc.c advances
 * the PIT only once per CPU step, and a native is one step, so without it a reloaded count
 * would also lose the cycles of the native before the OUT. (3.19 added those ticks back to
 * pc->pit[n].count directly; the pc.c helper replaced that.)
 *
 * Calls out of a native (atis_tick, flight_forces, demo_step, speaker_tone, speaker_off and
 * unknown sound_table targets) run the target the way the CPU would with the natives on: an
 * enabled native through native_call(), anything else single-stepped as original code.
 *
 * Interrupts (same scheme as 3.18): a native that is not nested in another one runs with an
 * undo log; when the timer or the keyboard would have raised an interrupt within its cycles,
 * its writes are undone, the CPU and device state are restored, and the call is handed back
 * to the original (its first instruction is performed, then the CPU continues in the
 * original routine, with interrupts). int8_timer runs with IF clear, so a timer tick due
 * inside it would only be delivered after its IRET either way; but the keyboard is latched
 * by the step in which it falls due, which sets the time of the next latch, so the hand-back
 * is kept for every entry. A native that spans the end of the front-end frame is handed back
 * too (S3F.2), so frames and the keys injected at their start fall where they do with the
 * original. int8_timer is also handed back when IF is set at its EOI: a callee
 * that ends with STI (atis_tick draws through blit_or) lets the original take a pending
 * interrupt between the EOI and the IRET. Under --verify (and nested in a native with a log)
 * they run plain. */
#include <SDL3/SDL.h>
#include <stddef.h>

#include "native.h"
#include "game/state.h"
#include "keys.h"
