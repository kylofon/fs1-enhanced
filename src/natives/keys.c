/* aileron/rudder += delta, saturating at clampv; then jno target / mov clampv / jmp target. */
static void control_add(Pc *pc, uint16_t at, uint16_t jno_end, uint16_t sat_end, uint16_t off, uint16_t delta,
                        uint16_t clampv, void (*next)(Pc *))
{
    run(pc, at, jno_end);
    bool of;
    wr16(pc, off, add_of(rd16(pc, off), delta, &of));
    if (!of) {
        taken(pc, (uint16_t)(jno_end - 2));
    } else {
        run(pc, jno_end, sat_end);
        wr16(pc, off, clampv);
    }
    next(pc);
}

