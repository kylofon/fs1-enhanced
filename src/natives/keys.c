    run(pc, 0x0970, 0x0995);
    cpu_push(c, REG(AX));
    cpu_push(c, REG(BX));
    cpu_push(c, REG(CX));
    cpu_push(c, REG(DX));
    cpu_push(c, REG(BP));
    cpu_push(c, REG(SI));
    cpu_push(c, REG(DI));
    cpu_push(c, SREG(DS));
    cpu_push(c, SREG(ES));
    REG(AX) = 0;
    SREG(DS) = mem_read16(pc, 0, 0x0120);
