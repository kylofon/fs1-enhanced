/* Natives for subphase 3.16 editor, presets, menus (see docs/PHASE3_PLAN.md and
 * docs/subphases/3.16.md).
 *
 * The routines are transliterated on the emulated registers, so every register, segment
 * register and memory byte (including the stack words written by CALL and PUSH) ends as the
 * original leaves it. Memory goes through the generated accessors of game/state.h, which use
 * the live DS: usermode_recall and editor_apply_state also run at start-up, with DS = 0686.
 *
 * Cycles: run(from, to) adds the cpu8086.c cost of every original instruction in [from, to)
 * (table editor_cycles.h, generated by tools/gen_editor_cycles.py), taken() adds the extra
 * cost of a jump that was taken. Every entry's .cycles is ENTRY_CYCLES and is subtracted
 * again, so a call costs exactly what the original costs.
 *
 * Calls out of a native (CALL in the original) go through call(): it pushes the return
 * address and runs the target the way the CPU would with the natives on: an enabled native
 * at a reached address runs its C function through native_call() (so the other natives of
 * this file, and those of 3.2, 3.9, 3.11, 3.17, ...), anything else is single-stepped as
 * original code. Interrupts are not delivered meanwhile.
 *
 * Interrupts. The timer handler (sound, clock, ATIS rate, flight_forces, demo_step) reads and
 * writes state that some of these routines write or read: the flight state (capture, apply),
 * the sound and ATIS-rate fields and the clock (user-mode recall, commit, ...). A native holds
 * interrupts until it returns, so when an interrupt would have arrived within the routine's
 * cycles, the result could differ from the original's, and the delayed timer ticks can merge.
 * In that case the native's writes are undone and the call is handed back to the original (as
 * 3.14 does; see entry_run): the first instruction is performed and the CPU continues in the
 * original routine, with interrupts. Under --verify the original runs without interrupts, so
 * they never hand back there.
 *
 * Not replaced (see the notes): editor_main 3640 and editor_get_input 3703, and
 * startup_menus 5CE9, wait in a loop for a key from the keyboard interrupt. --verify runs the
 * original without interrupts, so it could never return from a call bound there; such an
 * entry would end every campaign session with a step-cap mismatch. Their parts that end
 * with a RET are natives here; the key loops stay original.
 *
 * Backspace, 's' and 'l' are natives that continue in the key loop (no RET), so --verify cannot
 * check them; they are tested by comparing runs with the natives on and off. 's' and 'l' save
 * and load all presets to a host file (fs1_presets.bin, see preset_path()) instead of disk
 * track 26h. */
