{
    call(pc, 0x36E3);
    run(pc, 0x36E6, 0x36F3);
    SET_LO(DX, 0x20);
    ewr8(pc, REG(BX), 0x20);
    ewr8(pc, (uint16_t)(REG(BX) + 2), 0x20);
    ewr8(pc, (uint16_t)(REG(BX) + 4), 0x20);
    ret(pc, 0x36F3);
}

/* ---- 0050:369F editor_first_page, 368A editor_next_row, 36C1 editor_prev_row ------------- */

/* 36AC: editor_row = AL, draw the "-->" cursor, RET. */
static void at_36ac(Pc *pc)
{
    run(pc, 0x36AC, 0x36AF);
    gs_set_editor_row(pc, AL);
    call(pc, 0x36AF);
    run(pc, 0x36B2, 0x36C0);
    ewr8(pc, REG(BX), '-');
    ewr8(pc, (uint16_t)(REG(BX) + 2), '-');
    ewr8(pc, (uint16_t)(REG(BX) + 4), '>');
    ret(pc, 0x36C0);
}

/* 36A1: editor_page = AL, page text, fields, cursor on row 2. */
static void at_36a1(Pc *pc)
{
    run(pc, 0x36A1, 0x36A4);
    gs_set_editor_page(pc, AL);
    call(pc, 0x36A4);
    call(pc, 0x36A7);
    run(pc, 0x36AA, 0x36AC);
    SET_LO(AX, 2);
    at_36ac(pc);
}

static void b_first_page(Pc *pc)
{
    run(pc, 0x369F, 0x36A1);
    SET_LO(AX, 0);
    at_36a1(pc);
}

static void b_next_row(Pc *pc)
{
    call(pc, 0x368A);
    run(pc, 0x368D, 0x3696);
    SET_LO(AX, gs_editor_row(pc) + 2);
    if (AL != 0x2E) {
        taken(pc, 0x3694);
        at_36ac(pc);
        return;
    }
    run(pc, 0x3696, 0x369F);
    SET_LO(AX, gs_editor_page(pc) + 2);
    if (AL != 4) {
        taken(pc, 0x369D);
        at_36a1(pc);
        return;
    }
    b_first_page(pc);
}

static void b_prev_row(Pc *pc)
{
    call(pc, 0x36C1);
    run(pc, 0x36C4, 0x36CD);
    SET_LO(AX, gs_editor_row(pc) - 2);
    if (AL != 0) {
        taken(pc, 0x36CB);
        at_36ac(pc);
        return;
    }
    run(pc, 0x36CD, 0x36D4);
    SET_LO(AX, gs_editor_page(pc) - 2);
    if (!(AL & 0x80)) {
        taken(pc, 0x36D2);
    } else {
        run(pc, 0x36D4, 0x36D6);
        SET_LO(AX, 2);
    }
    run(pc, 0x36D6, 0x36D9);
    gs_set_editor_page(pc, AL);
    call(pc, 0x36D9);
    call(pc, 0x36DC);
    run(pc, 0x36DF, 0x36E3);
    SET_LO(AX, 0x2C);
    at_36ac(pc);
}

/* ---- 0050:3909 editor_page_text, 39DB editor_draw_page ------------------------------------ */

static void b_page_text(Pc *pc)
{
    run(pc, 0x3909, 0x3911);
    SET_HI(AX, 0x0F);
    REG(CX) = 0x3E8;
    REG(DI) = 0;
    for (;;) {
        run(pc, 0x3911, 0x3915);
        SET_LO(AX, rd8(pc, REG(SI)));
        REG(SI) = (uint16_t)(REG(SI) + dstep(pc, 1));
        ewr8(pc, REG(DI), AL);
        ewr8(pc, (uint16_t)(REG(DI) + 1), (uint8_t)(REG(AX) >> 8));
        REG(DI) = (uint16_t)(REG(DI) + dstep(pc, 2));
        if (--REG(CX) == 0)
            break;
        taken(pc, 0x3913);
    }
    ret(pc, 0x3915);
}

static void b_draw_page(Pc *pc)
{
    run(pc, 0x39DB, 0x39E5);
    uint8_t page = gs_editor_page(pc);
    REG(BX) = page;
    REG(SI) = rd16(pc, (uint16_t)(GS_EDITOR_PAGE_TEXTS + page));
    call(pc, 0x39E5);
    ret(pc, 0x39E8);
}

/* ---- 0050:39B2 editor_field_next, 396F editor_draw_fields, 39E9 editor_read_fields ------ */

static void b_field_next(Pc *pc)
{
    run(pc, 0x39B2, 0x39DA);
    uint16_t bx = gs_editor_field_rec(pc);
    uint8_t row = rd8(pc, (uint16_t)(bx + 1));
    REG(BX) = bx;
    gs_set_editor_row(pc, row);
    REG(DI) = row;
    gs_set_editor_field_scr(pc, (uint16_t)(rd16(pc, (uint16_t)(GS_EDITOR_ROW_OFFSETS + row)) + 0x0A));
    REG(AX) = (uint16_t)(rd8(pc, (uint16_t)(bx + 2)) + GS_EDITOR_VALUES);
    gs_set_editor_ptr(pc, REG(AX));
    gs_set_editor_field_rec(pc, (uint16_t)(gs_editor_field_rec(pc) + 3));
    ret(pc, 0x39DA);
}

/* 396F..397D / 39E9..39F7: editor_field_rec = the page's field list. */
static void field_list_start(Pc *pc, uint16_t at)
{
    run(pc, at, (uint16_t)(at + 0x0E));
    uint16_t bx = rd16(pc, (uint16_t)(GS_EDITOR_FIELD_LISTS + gs_editor_page(pc)));
    REG(BX) = bx;
    gs_set_editor_field_rec(pc, bx);
}

/* 397D / 39F7: DX = width of the next record; false (after RET) at the end of the list. */
static bool field_list_next(Pc *pc, uint16_t at)
{
    run(pc, at, (uint16_t)(at + 0x0C));
    REG(BX) = gs_editor_field_rec(pc);
    REG(DX) = rd8(pc, REG(BX));
    if (REG(DX) == 0) {
        ret(pc, (uint16_t)(at + 0x0C));
        return false;
    }
    taken(pc, (uint16_t)(at + 0x0A));
    return true;
}

static void b_draw_fields(Pc *pc)
{
    field_list_start(pc, 0x396F);
    while (field_list_next(pc, 0x397D)) {
        call(pc, 0x398A);
        run(pc, 0x398D, 0x399E);
        SET_LO(CX, 0);
        wr8(pc, GS_EDITOR_VALUE, 0);
        wr8(pc, (uint16_t)(GS_EDITOR_VALUE + 1), 0);
        wr8(pc, (uint16_t)(GS_EDITOR_VALUE + 2), 0);
        REG(SI) = 0;
        for (;;) {
            run(pc, 0x399E, 0x39AD);
            REG(BX) = gs_editor_ptr(pc);
            SET_LO(AX, rd8(pc, (uint16_t)(REG(BX) + REG(SI))));
            wr8(pc, (uint16_t)(GS_EDITOR_VALUE + REG(SI)), AL);
            REG(SI)++;
            if (REG(SI) == REG(DX))
                break;
            taken(pc, 0x39AB);
        }
        call(pc, 0x39AD);
        run(pc, 0x39B0, 0x39B2);
    }
}

static void b_read_fields(Pc *pc)
{
    field_list_start(pc, 0x39E9);
    while (field_list_next(pc, 0x39F7)) {
        call(pc, 0x3A04);
        run(pc, 0x3A07, 0x3A0A);
        REG(DI) = 5;
        for (;;) {
            run(pc, 0x3A0A, 0x3A12);
            wr8(pc, (uint16_t)(GS_EDITOR_DIGITS + REG(DI)), '0');
            if (--REG(DI) & 0x8000)
                break;
            taken(pc, 0x3A10);
        }
        run(pc, 0x3A12, 0x3A15);
        REG(SI) = 0;
        for (;;) {
            run(pc, 0x3A15, 0x3A20);
            REG(BX) = gs_editor_field_scr(pc);
            SET_LO(AX, erd8(pc, (uint16_t)(REG(BX) + REG(SI))));
            if (AL == 0x20) {
                taken(pc, 0x3A1E);
                break;
            }
            run(pc, 0x3A20, 0x3A23);
            REG(DI) = 4;
            for (;;) {
                run(pc, 0x3A23, 0x3A2E);
                uint8_t ah = rd8(pc, (uint16_t)(GS_EDITOR_DIGITS + REG(DI)));
                SET_HI(AX, ah);
                wr8(pc, (uint16_t)(GS_EDITOR_DIGITS + 1 + REG(DI)), ah);
                if (--REG(DI) & 0x8000)
                    break;
                taken(pc, 0x3A2C);
            }
            run(pc, 0x3A2E, 0x3A36);
            wr8(pc, GS_EDITOR_DIGITS, AL);
            REG(SI) = (uint16_t)(REG(SI) + 2);
        }
        call(pc, 0x3A36);
        run(pc, 0x3A39, 0x3A3C);
        REG(SI) = 0;
        for (;;) {
            run(pc, 0x3A3C, 0x3A4B);
            SET_LO(AX, rd8(pc, (uint16_t)(GS_EDITOR_VALUE + REG(SI))));
            REG(BX) = gs_editor_ptr(pc);
            wr8(pc, (uint16_t)(REG(BX) + REG(SI)), AL);
            REG(SI)++;
            if (REG(SI) == REG(DX))
                break;
            taken(pc, 0x3A49);
        }
        run(pc, 0x3A4B, 0x3A4D);
    }
}

/* ---- 0050:3A4D usermode_store, 3A52 usermode_recall ---------------------------------------- */

#define SLOT_SIZE 0x41

static void usermode_copy(Pc *pc, bool store)
{
    if (store)
        run(pc, 0x3A4D, 0x3A51);
    else
        run(pc, 0x3A52, 0x3A54);
    SET_LO(DX, store ? 1 : 0);
    run(pc, 0x3A54, 0x3A5E);
    gs_set_editor_ptr(pc, GS_USERMODE_SLOTS);
    SET_LO(CX, gs_usermode_cur(pc));
    for (;;) {
        run(pc, 0x3A5E, 0x3A62);
        SET_LO(CX, (uint8_t)REG(CX) - 1);
        if (REG(CX) & 0x80) {
            taken(pc, 0x3A60);
            break;
        }
        run(pc, 0x3A62, 0x3A69);
        gs_set_editor_ptr(pc, (uint16_t)(gs_editor_ptr(pc) + SLOT_SIZE));
    }
    run(pc, 0x3A69, 0x3A6F);
    REG(CX) = SLOT_SIZE - 1;
    REG(SI) = SLOT_SIZE - 1;
    for (;;) {
        run(pc, 0x3A6F, 0x3A73);
        if ((uint8_t)REG(DX) == 0) {
            taken(pc, 0x3A71);
            run(pc, 0x3A80, 0x3A8A);
            REG(BX) = gs_editor_ptr(pc);
            SET_LO(AX, rd8(pc, (uint16_t)(REG(BX) + REG(SI))));
            gs_set_editor_values_b(pc, REG(SI), AL);
        } else {
            run(pc, 0x3A73, 0x3A7F);
            SET_LO(AX, gs_editor_values_b(pc, REG(SI)));
            REG(BX) = gs_editor_ptr(pc);
            wr8(pc, (uint16_t)(REG(BX) + REG(SI)), AL);
        }
        run(pc, 0x3A8A, 0x3A8D);
        if (--REG(SI) & 0x8000)
            break;
        taken(pc, 0x3A8B);
    }
    run(pc, 0x3A8D, 0x3A92);
    gs_set_gear_down(pc, 0xFF);
    call(pc, 0x3A92);
    ret(pc, 0x3A95);
}

static void b_usermode_store(Pc *pc) { usermode_copy(pc, true); }
static void b_usermode_recall(Pc *pc) { usermode_copy(pc, false); }

